#!/usr/bin/env python3
"""Vendor the same highlight.js grammars as 1Panel; no Node/WebView runtime needed.

Usage: python3 scripts/vendor-preview-syntax.py /path/to/highlight.js
The generated resource is checked in. Normal builds never access another repository.
"""
import json
import pathlib
import sys

package = pathlib.Path(sys.argv[1])
version = json.loads((package / "package.json").read_text())["version"]
if version != "11.12.0":
    raise SystemExit(f"Review grammar updates before changing the pinned version: {version}")
languages = "bash c cpp css diff dockerfile go ini java javascript json lua makefile markdown nginx php properties protobuf python ruby rust sql typescript xml yaml".split()
resource = pathlib.Path(__file__).resolve().parent.parent / "Resources"
parts = ["// Generated by scripts/vendor-preview-syntax.py. highlight.js 11.12.0, BSD-3-Clause.\n// See PreviewSyntax.LICENSE.txt. Token offsets are UTF-16, like NSRange.\nvar previewSyntaxTokens = (() => {\n"]
parts.append("const core = {exports: {}};\n((module, exports) => {\n" + (package / "lib/core.js").read_text() + "\n})(core, core.exports);\nconst hljs = core.exports;\n")
for language in languages:
    source = (package / f"lib/languages/{language}.js").read_text()
    parts.append("{ const m = {exports: {}}; ((module, exports) => {\n" + source + f"\n}})(m, m.exports); hljs.registerLanguage('{language}', m.exports); }}\n")
parts.append(r'''
// Return token spans directly; no HTML generation or browser is involved.
class NativeEmitter {
  constructor() { this.offset = 0; this.scopes = []; this.spans = []; }
  addText(text) {
    const scope = this.scopes[this.scopes.length - 1];
    if (scope && text.length) {
      const last = this.spans[this.spans.length - 1];
      if (last && last[0] + last[1] === this.offset && last[2] === scope) last[1] += text.length;
      else this.spans.push([this.offset, text.length, scope]);
    }
    this.offset += text.length;
  }
  startScope(scope) { this.scopes.push(scope); }
  endScope() { this.scopes.pop(); }
  openNode(scope) { this.startScope(scope); }
  closeNode() { this.endScope(); }
  finalize() {}
  toHTML() { return ''; }
  __addSublanguage(emitter) {
    for (const [start, length, scope] of emitter.spans) this.spans.push([this.offset + start, length, scope]);
    this.offset += emitter.offset;
  }
}
hljs.configure({__emitter: NativeEmitter});
hljs.registerLanguage('hosts', () => ({contains: [
  {scope: 'comment', begin: /#/, end: /$/},
  {scope: 'number', begin: /^[ \t]*[\da-fA-F:.]+/},
  {scope: 'string', begin: /[^\s#]+/}
]}));
hljs.registerLanguage('ssh', () => ({contains: [
  {scope: 'comment', begin: /#/, end: /$/},
  {scope: 'keyword', begin: /^\s*(?:Host|Match|Include)\b/i},
  {scope: 'attribute', begin: /^\s*[a-zA-Z][\w-]*/},
  {scope: 'string', begin: /"/, end: /"/, contains: [{begin: /\\./}]},
  {scope: 'number', begin: /\b\d+\b/},
  {scope: 'literal', begin: /\b(?:yes|no|true|false|none)\b/i},
  {scope: 'string', begin: /[^\s=]+/}
]}));
return (text, language) => hljs.highlight(text, {language, ignoreIllegals: true})._emitter.spans;
})();
''')
(resource / "PreviewSyntax.js").write_text("".join(parts))
(resource / "PreviewSyntax.LICENSE.txt").write_text((package / "LICENSE").read_text())
print(f"Vendored highlight.js {version}: {len(languages)} grammars plus hosts/SSH")
